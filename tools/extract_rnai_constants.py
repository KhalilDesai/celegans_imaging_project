"""Extract the hardcoded normalisation dicts from the ORIGINAL development/RNAiClass.py.

They are scientific constants (DECISIONS R1) and must be bit-identical in the port. The
original file is Python 2 (not importable on py3), so each literal is located by text, its
braces matched, and the text evaluated with ``np.nan`` -> NaN. Writes src/embd/_rnai_constants.py.
"""
import math
import os
import sys

NAMES = ('controlOrigin', 'controlStd', 'rnaiMean', 'rnaiStd')
REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def extract(src_text):
    out = {}
    for name in NAMES:
        key = 'self.%s = {' % name
        i = src_text.index(key) + len(key) - 1
        depth, j = 0, i
        while True:
            c = src_text[j]
            if c == '{':
                depth += 1
            elif c == '}':
                depth -= 1
                if depth == 0:
                    break
            elif c == '#':  # skip comments to end of line
                j = src_text.index('\n', j)
                continue
            j += 1
        literal = src_text[i:j + 1]
        out[name] = eval(literal, {'np': type('np', (), {'nan': float('nan')})})
    return out


def main():
    src = open(os.path.join(REPO, 'development', 'RNAiClass.py'), encoding='latin-1').read()
    d = extract(src)
    lines = ['"""GENERATED by tools/extract_rnai_constants.py from development/RNAiClass.py (setOrigin).',
             '', 'Do not edit. Bit-identical copies of the hardcoded normalisation dicts (DECISIONS R1, R2).',
             'Key order follows the original literals.', '"""', 'nan = float("nan")', '']
    for name in NAMES:
        lines.append('%s = {' % name)
        for k, v in d[name].items():
            lines.append('    %r: %s,' % (k, 'nan' if isinstance(v, float) and math.isnan(v) else repr(float(v))))
        lines.append('}')
        lines.append('')
    with open(os.path.join(REPO, 'src', 'embd', '_rnai_constants.py'), 'w') as f:
        f.write('\n'.join(lines))
    print({n: len(d[n]) for n in NAMES})


if __name__ == '__main__':
    main()
